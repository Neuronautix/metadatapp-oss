# Default target is the repo this script lives in; `--root` overrides it so the
# generator can run against any checked-out repository (e.g. from a central
# reusable CI workflow). All path helpers read REPO_ROOT at call time.
REPO_ROOT = Path(__file__).resolve().parent.parent

GENERATOR = "scripts/generate-declarations.py"
# Bump SPEC_VERSION when the machine-readable shape changes; bump VOCAB_VERSION
# when the wording of the principle framework or capability labels changes.
SPEC_VERSION = 2
VOCAB_VERSION = 1

GENERATED_BANNER = (
    "GENERATED by scripts/generate-declarations.py — do not edit by hand. "
    "Update .declarations.yml or the repo evidence, then re-run "
    "`castor declarations` (or python3 scripts/generate-declarations.py)."
)

# Directories we never treat as evidence sources.
IGNORE_DIRS = {".git", "node_modules", "vendor", "var", "dist", "build", ".venv"}


# ---------------------------------------------------------------------------
# Repo inspection helpers
# ---------------------------------------------------------------------------


def exists(rel: str) -> bool:
    return (REPO_ROOT / rel).exists()


def glob_hits(pattern: str, limit: int = 1) -> list[str]:
    """Return up to `limit` repo-relative paths matching a glob, ignoring noise."""
    hits: list[str] = []
    for p in sorted(REPO_ROOT.glob(pattern)):
        rel = p.relative_to(REPO_ROOT)
        if any(part in IGNORE_DIRS for part in rel.parts):
            continue
        hits.append(str(rel))
        if len(hits) >= limit:
            break
    return hits


def collect_evidence(candidates: list[str]) -> list[str]:
    """Resolve a list of paths/globs to the subset that actually exists.

    Plain paths are kept if present; entries containing glob metacharacters are
    expanded (first match kept) so the evidence list stays short and stable.
    """
    found: list[str] = []
    for cand in candidates:
        if any(ch in cand for ch in "*?[") :
            found.extend(glob_hits(cand, limit=1))
        elif exists(cand):
            found.append(cand)
    # Stable, de-duplicated order.
    return sorted(dict.fromkeys(found))


def load_config() -> dict:
    config_path = REPO_ROOT / ".declarations.yml"
    if config_path.exists():
        return yaml.safe_load(config_path.read_text(encoding="utf-8")) or {}
    return {}


def detect_license() -> str:
    notice = REPO_ROOT / "NOTICE"
    if notice.exists() and "Affero" in notice.read_text(encoding="utf-8"):
        return "AGPL-3.0-or-later"
    lic = REPO_ROOT / "LICENSE"
    if lic.exists():
        head = lic.read_text(encoding="utf-8", errors="ignore")[:400]
        if "AFFERO" in head.upper():
            return "AGPL-3.0-or-later"
        if "Apache" in head:
            return "Apache-2.0"
        if "MIT" in head:
            return "MIT"
    return "UNLICENSED"


# ---------------------------------------------------------------------------
# Declaration model
# ---------------------------------------------------------------------------


@dataclass
class Declaration:
    key: str
    filename: str
    title: str
    applies_when: str
    # Candidate paths/globs that, when present, justify emitting the file.
    signals: list[str]
    # render(ctx, evidence) -> (frontmatter_extra: dict, body_markdown: str)
    render: Callable[["Context", list[str]], tuple[dict, str]]
    managed: bool = True

    def evidence(self) -> list[str]:
        return collect_evidence(self.signals)


@dataclass
class Context:
    config: dict
    project: dict = field(default_factory=dict)


@dataclass(frozen=True)
class Capability:
    """A single, evidence-backed thing a repo can demonstrate for a principle.

    `label` and `rationale` are owned centrally (the vocabulary), so the same
    capability reads identically in every repo. A capability is only ever
    claimed when at least one of its `signals` exists — no evidence, no claim.
    """

    id: str
    label: str
    rationale: str
    signals: list[str]

    def evidence(self) -> list[str]:
        return collect_evidence(self.signals)


# ---------------------------------------------------------------------------
# Front-matter + file rendering
# ---------------------------------------------------------------------------


def _yaml_block(data: dict) -> str:
    return yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100).rstrip()


def render_managed_file(decl: Declaration, frontmatter_extra: dict, body: str) -> str:
    """Compose `--- frontmatter --- \n body` deterministically."""
    body = body.strip() + "\n"
    body_hash = hashlib.sha256(body.encode("utf-8")).hexdigest()
    front: dict = {
        "_generated": GENERATED_BANNER,
        "declaration": decl.key,
        "title": decl.title,
        "spec_version": SPEC_VERSION,
        "generator": GENERATOR,
        "applies_when": decl.applies_when,
        "status": "active",
        "evidence": decl.evidence(),
    }
    front.update(frontmatter_extra)
    front["content_sha256"] = body_hash
    return f"---\n{_yaml_block(front)}\n---\n\n{body}"


def content_hash_of(path: Path) -> str:
    if not path.exists():
        return ""
    return hashlib.sha256(path.read_bytes()).hexdigest()



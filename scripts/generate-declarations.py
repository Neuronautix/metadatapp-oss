#!/usr/bin/env python3
"""
generate-declarations.py

Generate machine- and human-readable *repository declarations* from evidence
found in the repo. Each declaration is a Markdown file with a structured YAML
front matter (machine-readable) followed by a narrative body (human-readable),
plus a single machine index at `.well-known/repo-declarations.json`.

Declarations and when they are emitted:

  AI-declaration.md  -> when the repo uses AI (agents, prompts, models, MCP).
  FAIR.md            -> when the repo manages or describes research *data*.
  TRUST.md           -> when the repo does AI *knowledge management* (MCP/RAG,
                        prompt/eval corpora, governed knowledge bases).
  design.md          -> when the repo has a frontend. Hand-authored here, so the
                        generator only validates + indexes it (managed: false).

Other relevant declarations the generator can also emit (opt-in via config or
flags, documented in docs/architecture/repo-declarations.md):
  CITATION.cff, codemeta.json, llms.txt, SBOM.

Design goals
------------
* Deterministic: no timestamps inside generated artifacts, so `--check` is
  stable and CI can fail on drift. Provenance = generator + spec version +
  evidence + content hash.
* Evidence-driven: every claim is backed by a path that exists in the repo.
* Non-destructive: declarations marked `managed: false` are never overwritten.

Usage
-----
  python3 scripts/generate-declarations.py            # write/update files
  python3 scripts/generate-declarations.py --check    # CI: exit 1 on drift
  python3 scripts/generate-declarations.py --list      # show detected signals
"""


# Main pipeline
# ---------------------------------------------------------------------------


def compute_outputs() -> dict[str, str]:
    """Return {repo_relative_path: desired_content} for every managed artifact."""
    config = load_config()
    project = dict(config.get("project", {}) or {})
    project.setdefault("license", detect_license())
    ctx = Context(config=config, project=project)

    # Per-declaration `managed` override from config.
    overrides = config.get("declarations", {}) or {}

    outputs: dict[str, str] = {}
    active: list[tuple[Declaration, list[str]]] = []

    for decl in build_registry():
        ov = overrides.get(decl.key, {}) or {}
        if "managed" in ov:
            decl.managed = bool(ov["managed"])
        # Repos extend the generic trigger signals with their own paths.
        decl.signals = decl.signals + list(ov.get("signals", []) or [])

        evidence = decl.evidence()
        force = ov.get("force")
        applies = force if force is not None else bool(evidence)
        if not applies:
            continue

        active.append((decl, evidence))

        if not decl.managed:
            # Discovered but human-owned: index only, never overwrite.
            continue

        fm_extra, body = decl.render(ctx, evidence)
        outputs[decl.filename] = render_managed_file(decl, fm_extra, body)

    # Machine-only software metadata (emitted when we have a project name).
    extra_index: list[dict] = []
    meta_cfg = config.get("metadata", {}) or {}
    if project.get("name"):
        if meta_cfg.get("citation_cff", True):
            outputs["CITATION.cff"] = build_citation_cff(ctx)
            extra_index.append(
                {
                    "declaration": "citation",
                    "title": "Citation metadata",
                    "path": "CITATION.cff",
                    "applies_when": "repository is citable software",
                    "managed": True,
                    "evidence": collect_evidence(["LICENSE", "README.md"]),
                }
            )
        if meta_cfg.get("codemeta", True):
            outputs["codemeta.json"] = build_codemeta(ctx)
            extra_index.append(
                {
                    "declaration": "codemeta",
                    "title": "CodeMeta software metadata",
                    "path": "codemeta.json",
                    "applies_when": "repository is software with FAIR metadata",
                    "managed": True,
                    "evidence": collect_evidence(["LICENSE", "README.md"]),
                }
            )

    # Machine index + llms.txt.
    outputs[".well-known/repo-declarations.json"] = (
        json.dumps(build_index(ctx, active, outputs, extra_index), indent=2, ensure_ascii=False)
        + "\n"
    )
    outputs["llms.txt"] = build_llms_txt(ctx, active, extra_index)
    return outputs


def cmd_list() -> int:
    config = load_config()
    print("Detected repository declarations:\n")
    overrides = config.get("declarations", {}) or {}
    for decl in build_registry():
        ov = overrides.get(decl.key, {}) or {}
        decl.signals = decl.signals + list(ov.get("signals", []) or [])
        evidence = decl.evidence()
        force = ov.get("force")
        applies = force if force is not None else bool(evidence)
        managed = bool(ov.get("managed", decl.managed))
        flag = "ACTIVE " if applies else "skip   "
        own = "managed" if managed else "human-owned"
        print(f"  [{flag}] {decl.filename:<22} ({own}) — {decl.applies_when}")
        for e in evidence:
            print(f"            · {e}")
    return 0


def cmd_check() -> int:
    outputs = compute_outputs()
    drift = []
    for rel, content in outputs.items():
        path = REPO_ROOT / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            drift.append(rel)
    if drift:
        sys.stderr.write(
            "Repo declarations are out of date. Run "
            "`python3 scripts/generate-declarations.py` and commit:\n"
        )
        for rel in drift:
            sys.stderr.write(f"  - {rel}\n")
        return 1
    print("Repo declarations are up to date.")
    return 0


def cmd_write() -> int:
    outputs = compute_outputs()
    changed = []
    for rel, content in outputs.items():
        path = REPO_ROOT / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        changed.append(rel)
    if changed:
        print("Updated declarations:")
        for rel in changed:
            print(f"  - {rel}")
    else:
        print("Declarations already up to date.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate repository declarations.")
    parser.add_argument(
        "--root",
        type=Path,
        default=None,
        help="Target repository root (default: the repo this script lives in).",
    )
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="Fail if files are out of date (CI).")
    group.add_argument("--list", action="store_true", help="List detected declarations and exit.")
    args = parser.parse_args(argv)

    if args.root is not None:
        global REPO_ROOT
        REPO_ROOT = args.root.resolve()

    if args.list:
        return cmd_list()
    if args.check:
        return cmd_check()
    return cmd_write()


if __name__ == "__main__":
    raise SystemExit(main())

def _config_capabilities(config: dict, framework: str) -> dict[str, list[dict]]:
    return (config.get("capabilities", {}) or {}).get(framework, {}) or {}


def merge_capabilities(
    core: dict[str, list[Capability]], extra: dict[str, list[dict]]
) -> dict[str, list[Capability]]:
    """Merge config-supplied capabilities onto the generic core, by dimension.

    For each config entry: if its `id` already exists in that dimension, its
    `signals` are unioned onto the core capability (label/rationale overridden
    when provided); otherwise it is appended as a new capability. This is how a
    repo keeps the generic core but points capabilities at its own files —
    without editing the generator.
    """
    result: dict[str, list[Capability]] = {dim: list(caps) for dim, caps in core.items()}
    for dim, items in (extra or {}).items():
        bucket = result.setdefault(dim, [])
        index = {cap.id: i for i, cap in enumerate(bucket)}
        for item in items or []:
            cid = item["id"]
            signals = list(item.get("signals", []))
            if cid in index:
                existing = bucket[index[cid]]
                bucket[index[cid]] = Capability(
                    cid,
                    item.get("label", existing.label),
                    item.get("rationale", existing.rationale),
                    list(dict.fromkeys(existing.signals + signals)),
                )
            else:
                bucket.append(
                    Capability(cid, item.get("label", cid), item.get("rationale", ""), signals)
                )
    return result


def _assess_dimension(caps: list[Capability]) -> tuple[bool, list[dict], list[str]]:
    """Detect which capabilities in a dimension are supported by evidence.

    Returns (supported, capability_entries, flat_evidence).
    """
    entries: list[dict] = []
    flat: list[str] = []
    for cap in caps:
        ev = cap.evidence()
        if not ev:
            continue
        entries.append({"id": cap.id, "label": cap.label, "evidence": ev})
        flat.extend(ev)
    return bool(entries), entries, sorted(dict.fromkeys(flat))


def _render_principle(mark_name: str, definition: str, entries: list[dict],
                      notes: dict) -> str:
    """Compose one principle section from detected capabilities (no hardcoding)."""
    mark = "✅" if entries else "⚠️"
    lines = [f"### {mark} {mark_name}", "", definition, ""]
    if entries:
        for e in entries:
            ev = ", ".join(f"`{p}`" for p in e["evidence"])
            note = notes.get(e["id"])
            suffix = f" — {note}" if note else ""
            lines.append(f"- **{e['label']}** ({ev}){suffix}")
    else:
        lines.append("- _No supporting capability detected yet._")
    return "\n".join(lines) + "\n"


def render_fair(ctx: Context, evidence: list[str]) -> tuple[dict, str]:
    notes = ctx.config.get("capability_notes", {}) or {}
    caps = merge_capabilities(FAIR_CAPABILITIES, _config_capabilities(ctx.config, "fair"))
    fair_fm: dict = {}
    sections: list[str] = []
    for dim, (letter, name, definition) in FAIR_FRAMEWORK.items():
        supported, entries, flat = _assess_dimension(caps.get(dim, []))
        fair_fm[dim] = {"supported": supported, "capabilities": entries}
        sections.append(_render_principle(f"{letter} — {name}", definition, entries, notes))

    fm = {
        "schema": "https://w3id.org/fair/principles/0.1",
        "vocabulary_version": VOCAB_VERSION,
        "fair": fair_fm,
    }

    body = (
        "# FAIR Declaration\n\n"
        "This repository handles research **data** and metadata, so it publishes a FAIR\n"
        "self-assessment against the [FAIR principles](https://www.go-fair.org/fair-principles/)\n"
        "(Findable, Accessible, Interoperable, Reusable). The front matter is the\n"
        "machine-readable form; the sections below are the human narrative. Every claim\n"
        "below is a *capability detected in the repository* and links to its evidence.\n\n"
        "> Auto-generated assessment — `✅` means at least one supporting capability was\n"
        "> detected, `⚠️` means the principle is in scope but nothing was detected yet.\n\n"
        + "\n".join(sections)
        + "\n## Reviewing this assessment\n\n"
        "This is a starting point, not a certificate. Promote `⚠️` items to `✅` by adding\n"
        "the missing capability (identifiers, protocols, vocabularies, license metadata),\n"
        "then re-run the generator.\n"
    )
    return fm, body



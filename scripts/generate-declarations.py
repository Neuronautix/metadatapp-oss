def _split_name(person: dict) -> tuple[str, str]:
    """Return (given_names, family_name) from a config author entry."""
    if person.get("given-names") or person.get("family-names"):
        return person.get("given-names", ""), person.get("family-names", "")
    name = (person.get("name") or "").strip()
    if not name:
        return "", ""
    parts = name.split()
    if len(parts) == 1:
        return "", parts[0]
    return " ".join(parts[:-1]), parts[-1]


def detect_languages() -> list[str]:
    langs = []
    if exists("api") or glob_hits("**/*.php"):
        langs.append("PHP")
    if exists("osoma") or glob_hits("**/*.ts") or glob_hits("**/*.tsx"):
        langs.append("TypeScript")
    if glob_hits("scripts/*.py") or glob_hits("**/*.py"):
        langs.append("Python")
    return langs


def build_citation_cff(ctx: Context) -> str:
    """Citation File Format 1.2.0 (https://citation-file-format.github.io/)."""
    p = ctx.project
    authors = []
    for person in ctx.config.get("authors", []) or []:
        given, family = _split_name(person)
        entry: dict = {}
        if given:
            entry["given-names"] = given
        if family:
            entry["family-names"] = family
        if person.get("affiliation"):
            entry["affiliation"] = person["affiliation"]
        if entry:
            authors.append(entry)
    if not authors and p.get("organization"):
        authors.append({"name": p["organization"]})

    cff: dict = {
        "cff-version": "1.2.0",
        "message": "If you use this software, please cite it as below.",
        "title": p.get("name", "Project"),
        "type": "software",
    }
    if p.get("description"):
        cff["abstract"] = " ".join(p["description"].split())
    if authors:
        cff["authors"] = authors
    if p.get("license"):
        cff["license"] = p["license"]
    if p.get("repository"):
        cff["repository-code"] = p["repository"]
    if p.get("homepage"):
        cff["url"] = p["homepage"]
    if p.get("keywords"):
        cff["keywords"] = list(p["keywords"])
    if p.get("version"):
        cff["version"] = str(p["version"])
    if p.get("date_released"):
        cff["date-released"] = str(p["date_released"])

    header = (
        "# GENERATED by scripts/generate-declarations.py — do not edit by hand.\n"
        "# Update .declarations.yml, then re-run `castor declarations`.\n"
    )
    return header + yaml.safe_dump(cff, sort_keys=False, allow_unicode=True, width=100)


def build_codemeta(ctx: Context) -> str:
    """CodeMeta 2.0 JSON-LD software metadata (https://codemeta.github.io/)."""
    p = ctx.project
    authors = []
    for person in ctx.config.get("authors", []) or []:
        given, family = _split_name(person)
        node: dict = {"@type": "Person"}
        if given:
            node["givenName"] = given
        if family:
            node["familyName"] = family
        if person.get("affiliation"):
            node["affiliation"] = {"@type": "Organization", "name": person["affiliation"]}
        authors.append(node)

    doc: dict = {
        "@context": "https://doi.org/10.5063/schema/codemeta-2.0",
        "@type": "SoftwareSourceCode",
        "name": p.get("name"),
    }
    if p.get("description"):
        doc["description"] = " ".join(p["description"].split())
    if p.get("license"):
        doc["license"] = f"https://spdx.org/licenses/{p['license']}"
    if p.get("repository"):
        doc["codeRepository"] = p["repository"]
    if p.get("homepage"):
        doc["url"] = p["homepage"]
    if p.get("keywords"):
        doc["keywords"] = list(p["keywords"])
    if p.get("version"):
        doc["version"] = str(p["version"])
    langs = detect_languages()
    if langs:
        doc["programmingLanguage"] = langs
    if authors:
        doc["author"] = authors
    if p.get("organization"):
        doc["maintainer"] = {"@type": "Organization", "name": p["organization"]}
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


# ---------------------------------------------------------------------------
# Index + llms.txt
# ---------------------------------------------------------------------------


def build_index(
    ctx: Context,
    active: list[tuple[Declaration, list[str]]],
    rendered: dict[str, str],
    extra: list[dict] | None = None,
) -> dict:
    entries = []
    for decl, evidence in active:
        # Hash the content we are about to write (managed) or what is on disk
        # (human-owned), so the index never drifts against freshly-written files.
        if decl.filename in rendered:
            sha = hashlib.sha256(rendered[decl.filename].encode("utf-8")).hexdigest()
        else:
            sha = content_hash_of(REPO_ROOT / decl.filename)
        entries.append(
            {
                "declaration": decl.key,
                "title": decl.title,
                "path": decl.filename,
                "applies_when": decl.applies_when,
                "managed": decl.managed,
                "evidence": evidence,
                "content_sha256": sha,
            }
        )
    for item in extra or []:
        path = item["path"]
        sha = (
            hashlib.sha256(rendered[path].encode("utf-8")).hexdigest()
            if path in rendered
            else content_hash_of(REPO_ROOT / path)
        )
        entries.append({**item, "content_sha256": sha})
    return {
        "$schema": "https://w3id.org/repo-declarations/v1",
        "spec_version": SPEC_VERSION,
        "generator": GENERATOR,
        "project": {
            "name": ctx.project.get("name"),
            "repository": ctx.project.get("repository"),
            "license": ctx.project.get("license"),
        },
        "declarations": entries,
    }


def build_llms_txt(
    ctx: Context,
    active: list[tuple[Declaration, list[str]]],
    extra: list[dict] | None = None,
) -> str:
    name = ctx.project.get("name", "Project")
    desc = (ctx.project.get("description") or "").strip()
    lines = [f"# {name}", ""]
    if desc:
        lines += [f"> {desc}", ""]
    lines += [
        "This file helps LLMs and AI agents discover the repository's machine- and",
        "human-readable declarations.",
        "",
        "## Declarations",
        "",
    ]
    for decl, _ in active:
        lines.append(f"- [{decl.title}](./{decl.filename}): {decl.applies_when}")
    if extra:
        lines += ["", "## Machine metadata", ""]
        for item in extra:
            lines.append(f"- [{item['title']}](./{item['path']}): {item['applies_when']}")
    lines += [
        "",
        "## Index",
        "",
        "- [Machine-readable index](./.well-known/repo-declarations.json)",
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"



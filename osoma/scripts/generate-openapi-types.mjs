import fs from 'fs'
import path from 'path'

const specPath = path.join(process.cwd(), 'resources/metadatapp.json')
const outPath = path.join(process.cwd(), 'src', 'metadatapp', 'openapi-types.ts')

const spec = JSON.parse(fs.readFileSync(specPath, 'utf8'))
const schemas = spec.components?.schemas ?? {}

const normalizeType = (value) => {
  if (!value) return []
  if (Array.isArray(value)) return value.map(String)
  return [String(value)]
}

const refToType = (ref) => {
  const name = ref.replace('#/components/schemas/', '')
  return `components['schemas'][${JSON.stringify(name)}]`
}

const renderEnum = (values) => values.map((v) => JSON.stringify(v)).join(' | ') || 'string'

const renderType = (schema) => {
  if (!schema) return 'any'
  if (schema.$ref) return refToType(schema.$ref)

  const types = normalizeType(schema.type)
  const nullable = types.includes('null') || schema.nullable === true
  const nonNullTypes = types.filter((t) => t !== 'null')

  if (schema.oneOf || schema.anyOf) {
    const list = schema.oneOf ?? schema.anyOf ?? []
    const union = list.map(renderType).join(' | ') || 'any'
    return nullable ? `${union} | null` : union
  }

  if (schema.allOf) {
    const intersection = schema.allOf.map(renderType).join(' & ') || 'any'
    return nullable ? `${intersection} | null` : intersection
  }

  if (schema.enum) {
    const base = renderEnum(schema.enum)
    return nullable ? `${base} | null` : base
  }

  if (schema.items || nonNullTypes.includes('array')) {
    const itemSchema = schema.items ?? {}
    const itemType = Array.isArray(itemSchema)
      ? itemSchema.map(renderType).join(' | ')
      : renderType(itemSchema)
    const base = `${itemType}[]`
    return nullable ? `${base} | null` : base
  }

  if (schema.properties || nonNullTypes.includes('object')) {
    const required = new Set(schema.required ?? [])
    const props = schema.properties ?? {}
    const lines = ['{']
    for (const [key, propSchema] of Object.entries(props)) {
      const optional = required.has(key) ? '' : '?'
      lines.push(`  ${JSON.stringify(key)}${optional}: ${renderType(propSchema)};`)
    }
    if (schema.additionalProperties) {
      const apSchema = schema.additionalProperties === true ? {} : schema.additionalProperties
      lines.push(`  [key: string]: ${renderType(apSchema)};`)
    }
    lines.push('}')
    const base = lines.join('\n')
    return nullable ? `${base} | null` : base
  }

  if (nonNullTypes.includes('integer') || nonNullTypes.includes('number')) {
    return nullable ? 'number | null' : 'number'
  }
  if (nonNullTypes.includes('boolean')) {
    return nullable ? 'boolean | null' : 'boolean'
  }
  if (nonNullTypes.includes('string')) {
    return nullable ? 'string | null' : 'string'
  }

  return nullable ? 'any | null' : 'any'
}

const lines = []
lines.push('// Generated by scripts/generate-openapi-types.mjs')
lines.push('// Source: osoma/resources/metadatapp.json')
lines.push('')
lines.push('export interface components {')
lines.push('  schemas: {')

for (const [name, schema] of Object.entries(schemas)) {
  const type = renderType(schema)
  lines.push(`    ${JSON.stringify(name)}: ${type};`)
}

lines.push('  }')
lines.push('}')
lines.push('')
lines.push('export type SchemaRef = keyof components[\'schemas\']')
lines.push('export type SchemaType<Ref extends SchemaRef> = components[\'schemas\'][Ref]')

fs.writeFileSync(outPath, lines.join('\n'))
console.log(`Generated ${outPath}`)

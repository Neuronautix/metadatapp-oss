import type { Subject } from '@/domain/resources.ts'
import { cages, racks, rooms } from '@/mocks/data/tecniplast.ts'

const rackMap = new Map(racks.map((rack) => [rack.id, rack]))
const roomMap = new Map(rooms.map((room) => [room.id, room]))

const buildCageInfo = (cageId: string) => {
  const cage = cages.find((item) => item.id === cageId)
  const rack = cage ? rackMap.get(cage.rackId) : null
  const room = rack ? roomMap.get(rack.roomId) : null
  return {
    cageId,
    cageLabel: cage?.label ?? cageId,
    cageRoom: room?.name ?? 'Unknown room',
    cageRack: rack?.label ?? 'Unknown rack',
  }
}

